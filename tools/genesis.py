"""Reproduce the experimental genesis constants using real RandomX."""
import argparse, hashlib, json, struct
from pathlib import Path
from rx import RandomX

# The public testnet is already in use. The separate MAIN entry is an experimental candidate.
GENESIS_PARAMETERS = {
    'TEST': (1794614400, 0x207fffff),
    'MAIN': (1794614400, 0x207fffff),
}
POW_LIMIT = 0x7fffff << 232

def target_from_bits(bits):
    exponent = bits >> 24
    mantissa = bits & 0x7fffff
    shift = 8 * (exponent - 3)
    target = mantissa << shift if shift >= 0 else mantissa >> -shift
    if bits & 0x800000 or not 0 < target <= POW_LIMIT:
        raise ValueError(f'Invalid genesis target: {bits:#x}')
    return target

def sha(data): return hashlib.sha256(hashlib.sha256(data).digest()).digest()
def genesis_parts(label):
    timestamp, bits = GENESIS_PARAMETERS[label]
    phrase = ('Obsolete Coin '+label.lower()+': A new beginning.').encode()
    seed = hashlib.sha256(('Obsolete Coin RandomX '+label.lower()+' v0.2').encode()).digest()
    anchor = bytes([0x54 if label == 'TEST' else 0x4d])*32
    script = bytes.fromhex('04ffff001d0104') + bytes([len(phrase)]) + phrase
    tx = (struct.pack('<I',1)+b'\x01'+bytes(32)+bytes.fromhex('ffffffff')+
          bytes([len(script)])+script+bytes.fromhex('ffffffff')+b'\x01'+bytes(8)+
          b'\x22\x6a\x20'+anchor+bytes(4))
    merkle = sha(tx)
    head = struct.pack('<I',1)+bytes(32)+merkle+struct.pack('<II',timestamp,bits)
    return phrase.decode(), seed, merkle, head

def generate(library):
    records = {}
    for label, (_, bits) in GENESIS_PARAMETERS.items():
        target = target_from_bits(bits)
        phrase,seed,merkle,head=genesis_parts(label)
        with RandomX(library,seed) as rx:
            for nonce in range(100000):
                header=head+struct.pack('<I',nonce)
                work=rx.hash(header)
                if int.from_bytes(work,'little')<=target: break
            else: raise RuntimeError('No genesis nonce found')
        records[label]={'phrase':phrase,'seed':seed[::-1].hex(),'nonce':nonce,
                        'merkle':merkle[::-1].hex(),'hash':sha(header)[::-1].hex(),
                        'randomx_hash':work[::-1].hex()}
    lines=['// Deterministic experimental genesis. Generated by tools/genesis.py.',
           '#ifndef OBSOLETE_GENESIS_H','#define OBSOLETE_GENESIS_H',
           '#include <cstdint>']
    for label,record in records.items():
        timestamp, bits = GENESIS_PARAMETERS[label]
        lines.append(f'constexpr uint32_t OBSOLETE_{label}_TIME = {timestamp};')
        lines.append(f'constexpr uint32_t OBSOLETE_{label}_BITS = 0x{bits:x};')
        for field in ('phrase','seed','nonce','merkle','hash'):
            name=f'OBSOLETE_{label}_{field.upper()}'
            if field=='nonce': lines.append(f'constexpr uint32_t {name} = {record[field]};')
            else: lines.append(f'constexpr const char* {name} = "{record[field]}";')
    lines.append('#endif')
    return '\n'.join(lines)+'\n',records

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--library',required=True);p.add_argument('--verify',action='store_true');a=p.parse_args()
    root=Path(__file__).resolve().parents[1]
    header,records=generate(Path(a.library).resolve())
    dest=root/'src/consensus/obsolete_genesis.h'
    if a.verify:
        if dest.read_text()!=header: raise SystemExit('Genesis differs from pinned constants')
        if json.loads((root/'docs/genesis.json').read_text()) != records:
            raise SystemExit('Genesis differs from published proof vectors')
    else:
        if dest.exists() and dest.read_text()!=header: raise SystemExit('Refusing to overwrite different genesis')
        dest.write_text(header,encoding='utf-8',newline='\n')
        (root/'docs/genesis.json').write_text(json.dumps(records,indent=2)+'\n')
    print(json.dumps(records,indent=2))
